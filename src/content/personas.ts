const BY_ID = new Map(BLOG_PERSONAS.map((p) => [p.id, p]));

/** 프런트 드롭다운용 메타(프롬프트 본문 제외 — 서버 전용 유지). */
export function listPersonas(): Array<{ id: string; label: string; desc: string }> {
  return BLOG_PERSONAS.map(({ id, label, desc }) => ({ id, label, desc }));
}

/** 페르소나 id(+custom 시 자유 텍스트) → 작가 시스템 프롬프트에 주입할 말투 지침. 없으면 ''(현행 동작 유지). */
export function personaPrompt(id?: string, customText?: string): string {
  if (!id) return '';
  if (id === 'custom') {
    const t = (customText ?? '').trim().slice(0, 1000);
    if (!t) return '';
    return `${HEAD}\n${t}\n위 말투를 최우선으로 적용하되, 구체 수치·1인칭 근거·문장 리듬 변주와 AI 티 금지 원칙은 유지한다.`;
  }
  return BY_ID.get(id)?.prompt ?? '';
}
